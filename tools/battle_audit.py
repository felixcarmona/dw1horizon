    rows=[]
    for r in data['bosses']:
        name=r[0].split(' ',1)[1] if ':' in r[0] else r[0]
        if r[1]==300:name+=' (actor)'
        if r[0].startswith('MGEN99:0'):name+=' (final)'
        elif name=='Machinedramon':name+=' (repeat)'
        rows.append([name,f'{r[1]:,} / {r[3]}',f'{r[5]} → {r[6]}',f'{r[7]} → {r[8]}',f'{r[7]*3} → {r[8]*3} s',r[10]])
