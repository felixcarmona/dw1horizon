    ax.plot(xs,[stat_power(10000,x,rules,True)/10000 for x in xs],label='Original',color='#8b929c',lw=3)
    ax.plot(xs,[stat_power(10000,x,rules)/10000 for x in xs],label='Bounded extension',color='#167c87',lw=3)
    ax.axvline(500,color='#555555',ls=':',lw=1)
    ax.axhline(3,color='#555555',ls=':',lw=1)
