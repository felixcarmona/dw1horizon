def mask(word,gap=1):
    """-> dict (x,y)->1.0 or 0.5 ink, width"""
    m={}; x=0
    for i,ch in enumerate(word):
        rows=G[ch]; w=max(len(r) for r in rows)
        for y,r in enumerate(rows):
            for dx,c in enumerate(r):
                if c=='#': m[(x+dx,y)]=1.0
                elif c=='+': m[(x+dx,y)]=0.5
        x+=w+(gap if i<len(word)-1 else 0)
    return m,x
