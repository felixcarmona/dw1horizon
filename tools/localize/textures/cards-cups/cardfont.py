"""Card strip font: our own bold Latin pixel font for the card name strip (rows 0-9: 0-7 cap height,
2-7 x-height, 8-9 descender). '#' ink, '+' half-tone ink (rounded corners)."""
G={}
def g(ch,rows):
    rows=rows.split('/')
    G[ch]=rows+['']*(10-len(rows))
def lc(ch,body,asc=('','')):  # lowercase: body starts at row 2
    w=max(len(r) for r in body.split('/'))
    rows=[asc[0] or '.'*w, asc[1] or '.'*w]+body.split('/')
    G[ch]=rows+['']*(10-len(rows))
