"""Our bold serif (Times-bold-like) for the cup taglines, 11-row caps, drawn upright; slant applied at render.
'#' full ink, '+' half coverage. Rows 11-12 = below baseline (comma)."""
G={}
import re
def thin(r):
    w=len(r)
    def f(m):
        return '##+' if m.start()<=w/2-1 else '+##'
    return re.sub(r'(?<!#)###(?!#)',f,r)
def g(ch,s): G[ch]=[thin(r) for r in s.split('/')]
g('V','####..###/.###...+#./.+##...#+./..###..#../..+##.+#../...##+#+../...+###.../....###.../....+#+.../.....#..../..........')
