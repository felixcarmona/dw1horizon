def layout(text,gap=2,slant=0.12):
    """-> dict (x,y)->coverage (float x positions resolved), width"""
    cov={}; x=0
    for i,ch in enumerate(text):
        rows=G[ch]; w=max(len(r) for r in rows)
        for y,r in enumerate(rows):
            off=(10-y)*slant; io=int(off//1); f=off-io
            for dx,c in enumerate(r):
                a={'#':1.0,'+':0.5}.get(c,0)
                if not a: continue
                for (px_,wt) in ((x+dx+io,1-f),(x+dx+io+1,f)):
                    if wt>0: cov[(px_,y)]=min(1.0,cov.get((px_,y),0)+a*wt)
        x+=w+(gap if i<len(text)-1 else 0)
    return cov,x+2
