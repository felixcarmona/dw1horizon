"""Our thin antialiased sans for the GRADE banners' white lines (9-row caps).
'#'=idx 0x00 white, ':'=0x10, '+'=0x0a, '-'=0x02, '.'=transparent 0xff. Rows -2,-1 (accents) via ACC."""
IDX={'#':0x00,':':0x10,'+':0x0a,'-':0x02}
G={}
def g(ch,s,acc=None): G[ch]=(s.split('/'),acc)
g('A','...-+-.../...+#+.../..-#-#-../..+#.#+../.-#...#-./.+#####+./.#+...+#./+#.....#+/#+.....+#')
g('B','+++++-./#+..-#+/#+...+#/#+..-#-/#####:./#+..-#+/#+...+#/#+..-#+/#####-.')
g('C','..-+++-./.:#+..+#/.#+...../-#....../+#....../-#....../.#+...-#/.:#+..+#/..-+##+-')
g('D','+++++-../#+..+#-./#+...-#./#+....#+/#+....#+/#+....#+/#+...-#./#+..+#-./#####-..')
g('E','++++++/#+..../#+..../#+..../#####:/#+..../#+..../#+..../#####+')
g('G','..-+++-../.:#+..+#:/.#+....../-#......./+#...+###/-#......#/.#+....+#/.:#+..+##/..-+##+-#')
g('I','+-/#-/#-/#-/#-/#-/#-/#-/#-')
g('Í','+-/#-/#-/#-/#-/#-/#-/#-/#-',['.-#','-#.'])
g('L','+-..../#+..../#+..../#+..../#+..../#+..../#+..../#+..../#####+')
g('M','++.....++/##-...-##/##+...+##/#+#..-#+#/#+:+.+:+#/#+-#.#-+#/#+.##+.+#/#+.+#+.+#/#+..#..+#')
g('N','+-....+/##-...#/##+...#/#+#-..#/#+-#-.#/#+.-#-#/#+..-##/#+...+#/#+....#')
g('O','..-+++-../.:#+..+#:/.#+....+#/-#.....-#/+#......#/-#.....-#/.#+....+#/.:#+..+#:/..-+##+-.')
g('R','+++++-./#+..-#+/#+...+#/#+..-#+/#####-./#+..+#./#+...#+/#+...-#/#+....#')
g('S','.-+++-./-#-..+#/+#...../-#-..../.-+##+-/....-#+/.....+#/#+..-#-/-+##+-.')
g('T','+++++++/...#.../...#.../...#.../...#.../...#.../...#.../...#.../...#...')
g('U','#+.....+#/#+.....+#/#+.....+#/#+.....+#/#+.....+#/#+.....+#/.#+...+#./.:#+.+#:/..-+#+-.')
g('e','......./......./..-++-./.:#..#:/-#....#/+#####+/-#...../.:#..-#/..-+#+.')
g('l','+-/#+/#+/#+/#+/#+/#+/#+/#+')
g('·','-++-/+##+/+:#+/--+-')
g(' ','..')
def layout(text,gap=2):
    """-> list of (x,y,idx) relative to cap top, width"""
    out=[];x=0
    for i,ch in enumerate(text):
        rows,acc=G[ch]; w=max(len(r) for r in rows)
        for y,r in enumerate(rows):
            for dx,c in enumerate(r):
                if c in IDX: out.append((x+dx,y,IDX[c]))
        if acc:
            for j,r in enumerate(acc):
                for dx,c in enumerate(r):
                    if c in IDX: out.append((x+dx,j-2,IDX[c]))
        x+=w+(gap if i<len(text)-1 else 0)
    return out,x
