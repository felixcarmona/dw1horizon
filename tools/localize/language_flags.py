"""Exact title-picker flags, encoded as colour runs without changing any pixel."""
import struct
from pathlib import Path


def pixel(lang,x,y):
    dx,dy=x-12,y-8
    diagonal,other=abs(2*x-3*y),abs(2*(23-x)-3*y)
    if lang == 0:
        if 11 <= x <= 12 or 7 <= y <= 8:return 0xd82038
        if 9 <= x <= 14 or 5 <= y <= 10:return 0xffffff
        if diagonal < 2 or other < 2:return 0xd82038
        return 0xffffff if diagonal < 5 or other < 5 else 0x163478
    if lang == 1:return 0xc82030 if y < 4 or y >= 12 else 0xffcf30
    if lang == 2:
        if dx*dx+dy*dy < 19:return 0xffffff if dy == 0 else 0x16449a
        return 0xffd632 if abs(dx)*7+abs(dy)*10 < 70 else 0x129044
    if lang == 3:return 0x19489c if x < 8 else 0xffffff if x < 16 else 0xe83040
    if lang == 4:return 0x101010 if y < 5 else 0xd82430 if y < 11 else 0xffce30
    if lang == 5:return 0x15945a if x < 8 else 0xffffff if x < 16 else 0xda3042
    if lang == 6:return 0xc82042 if dx*dx+dy*dy < 21 else 0xffffff
    if lang == 7:return 0xda2430 if y in (1,2,5,6,9,10,13,14) else 0xffd23a
    raise ValueError('the Chinese language uses a label without a flag')


def tables():
    palettes,offsets,runs=[],[],bytearray()
    for lang in range(8):
        offsets.append(len(runs));palette=[]
        for y in range(16):
            x=0
            while x<24:
                color=pixel(lang,x,y);end=x+1
                while end<24 and pixel(lang,end,y)==color:end+=1
                if color not in palette:palette.append(color)
                runs.append(palette.index(color)*32+end-x);x=end
        assert len(palette)<=4
        palettes.append(palette+[0]*(4-len(palette)))
    return palettes,offsets,bytes(runs)


def payload(kind):
    palettes,offsets,runs=tables()
    if kind=='palette':return struct.pack('<32I',*(v for row in palettes for v in row))
    if kind=='offset':return struct.pack('<8H',*offsets)
    if kind=='runs':return runs
    raise ValueError('unknown flag table')


def header():
    palettes,offsets,runs=tables()
    return ('/* Exact pixel runs generated by tools/localize/language_flags.py. */\n'
            'static const uint32_t MOD_FLAG_PALETTE[8][4] = {\n'+
            ''.join('    { '+', '.join(f'0x{x:06x}' for x in row)+' },\n' for row in palettes)+
            '};\nstatic const uint16_t MOD_FLAG_OFFSET[8] = { '+', '.join(map(str,offsets))+' };\n'+
            f'static const uint8_t MOD_FLAG_RUNS[{len(runs)}] = {{\n'+
            ''.join('    '+', '.join(map(str,runs[i:i+24]))+',\n' for i in range(0,len(runs),24))+'};\n')


def main():
    import argparse
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('tree',type=Path);p.add_argument('--write',action='store_true');a=p.parse_args()
    target=a.tree/'src/main/language_flags.h';text=header()
    if a.write:target.write_text(text)
    elif target.read_text()!=text:raise SystemExit('title flag tables differ; regenerate with --write')
    print('Eight flags: every colour run matches its original pixels')


if __name__=='__main__':main()
