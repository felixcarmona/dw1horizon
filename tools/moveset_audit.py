#!/usr/bin/env python3
"""Census encounter move variety and weak melee weighting from owned sources.

--maps overlays final generated MAP rows, including DWS placements. A zero
chase range is reported separately: it can mean a story fight or a town actor.
Flags are review candidates, not evidence of a measured animation stunlock.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
import content
import dwmap
import species
from enemy_movesets import load as load_profiles


def census(maps=None):
    species_rows = species.load_content()
    techniques = content.load_techniques()
    names = {name: sid for sid, name in content._species_names().items()}
    maps_rows = {}
    for path in sorted((ROOT / 'content/maps').glob('*.json')):
        maps_rows[path.stem] = [dict(slot=d['slot'], species=names[d['species']] if isinstance(d['species'], str) else d['species'],
                                     chase=d.get('range', 0), moves=d['moves'], weights=d['prios'])
                                for d in json.loads(path.read_text()).get('digimon', [])]
    for folder in maps or []:
        for path in sorted(Path(folder).rglob('*.MAP')):
            maps_rows[path.stem] = [dict(slot=i, species=d['type'], chase=d['trackingRange'],
                                         moves=[d[f'move{k}'] for k in range(4)], weights=[d[f'prio{k}'] for k in range(4)])
                                    for i, d in enumerate(dwmap.MapFile(path.read_bytes()).digimon)]
    rows = []
    for name, entries in sorted(maps_rows.items()):
        for d in entries:
            sp = species_rows.get(d['species'])
            if not sp or sp['level'] == 'none':
                continue
            techs = species.techniques_from_json(sp.get('techniques'), sp['_path'])
            moves = []
            for slot, weight in zip(d['moves'], d['weights']):
                tid = techs[slot - 46] if 46 <= slot < 46 + len(techs) else 255
                tech = techniques.get(tid, {})
                moves.append(dict(slot=slot, id=tid, name=tech.get('name', 'idle/absent'), weight=weight,
                                  power=tech.get('power', 0), range=tech.get('range', 0)))
            # Counter is reactive: BTL_isMoveUsable rejects it for the normal
            # selection lottery even though it has a nonzero damage power.
            damaging = {m['id'] for m in moves if m['weight'] and m['id'] < 58 and m['id'] != 45
                        and m['power'] > 0 and m['range'] != 4}
            weak = any(m['id'] < 58 and m['weight'] >= 30 and 0 < m['power'] <= 100 and m['range'] == 1 for m in moves)
            rows.append(dict(map=name, **d, name=sp['name'], level=sp['level'], choices=moves,
                             damagingChoices=len(damaging), narrow=len(damaging) <= 2, weakMelee=weak))
    return rows


def report(rows):
    lines = ['# Enemy moveset census', '',
             'Generated by `python3 tools/moveset_audit.py`. Add `--maps build/NAME-maps/screens --maps build/NAME/story-maps --maps build/NAME/balance-maps/maps` for final DWS placements.', '',
             'Flags: at most two distinct weighted ordinary damaging techniques (excluding reactive Counter); or a melee technique of power 1–100 with weight >=30. '
             'Move timings and observed interruption are not inferred from power. Zero chase range includes both scripted fights and noncombat actors. '
             'Counts are placements, not encounter probabilities. NEW DIGIMON on technique slots are shown.', '']
    for chasing in (True, False):
        group = [r for r in rows if bool(r['chase']) == chasing]
        flags = [r for r in group if r['narrow'] or r['weakMelee']]
        lines += [f'## {"Chasing placements" if chasing else "Story or actor placements"}', '',
                  f'{len(group)} rows; {sum(r["narrow"] for r in group)} narrow; {sum(r["weakMelee"] for r in group)} weak-melee candidates.', '',
                  '| Map:slot | Species | Damage choices | Weak melee | Choices (weight) |',
                  '| --- | --- | --- | --- | --- |']
        for r in flags:
            choices = ', '.join(f'{m["name"]} ({m["weight"]})' for m in r['choices'])
            lines.append(f'| {r["map"]}:{r["slot"]} | {r["species"]} {r["name"]} | {r["damagingChoices"]} | {r["weakMelee"]} | {choices} |')
        lines.append('')
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--maps', type=Path, action='append', help='final map folder; repeat for added screens and native story edits')
    ap.add_argument('--out', type=Path, default=Path('build/moveset-audit'))
    args = ap.parse_args()
    profiles = load_profiles()
    rows = census(args.maps)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / 'audit.json').write_text(json.dumps(rows, indent=2) + '\n')
    (args.out / 'audit.md').write_text(report(rows) + '\n')
    print(f'{len(rows)} placements, {len(profiles)} validated encounter profiles; {args.out}/audit.md')


if __name__ == '__main__':
    main()
