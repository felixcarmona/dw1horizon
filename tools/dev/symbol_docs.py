#!/usr/bin/env python3
"""Generates a symbols reference (default build/symbols.md): the executable's global variables (from
decomp/config/us/symbols.txt) grouped by the C file that defines them, with
RAM address, size and type when known.

Usage:  symbol_docs.py [output.md]
"""

from pathlib import Path as _DevPath
import sys as _dev_sys
_DEV_ROOT = str(next(p for p in _DevPath(__file__).resolve().parents if (p / "tools").is_dir()))
_dev_sys.path.insert(0, _DEV_ROOT)
_dev_sys.path.insert(0, str(_DevPath(_DEV_ROOT) / "tools"))
import os, re, sys
from collections import defaultdict

ROOT = _DEV_ROOT
D = os.path.join(ROOT, 'decomp')
SYMS = os.path.join(D, 'config/us/symbols.txt')
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'build/symbols.md')

# data symbols: UPPERCASE names (the decompilation's convention)
syms = {}
for line in open(SYMS):
    m = re.match(r'([A-Z][A-Z0-9_]+)\s*=\s*(0x[0-9A-Fa-f]+);\s*(?://\s*(.*))?', line)
    if m:
        note = m.group(3) or ''
        size = re.search(r'size:(0x[0-9A-Fa-f]+)', note); typ = re.search(r'type:(\S+)', note)
        syms[m.group(1)] = (int(m.group(2), 16), int(size.group(1), 16) if size else None, typ.group(1) if typ else '')

# where each one is defined: file-level declaration in src/
defs = {}; decl_re = re.compile(r'^(?:extern\s+)?([A-Za-z_][A-Za-z0-9_ *]*?)\s+\**\s*([A-Z][A-Z0-9_]+)\s*(\[[^;=]*\])?\s*(=|;)')
for sub in sorted(os.listdir(os.path.join(D, 'src'))):
    for fn in sorted(os.listdir(os.path.join(D, 'src', sub))):
        if not fn.endswith('.c'): continue
        path = f'src/{sub}/{fn}'
        for ln, line in enumerate(open(os.path.join(D, path), encoding='utf-8', errors='replace'), 1):
            if line.startswith(('extern', ' ', '\t', '/', '*', '#', '}')): continue
            m = decl_re.match(line)
            if m and m.group(2) in syms and m.group(2) not in defs:
                defs[m.group(2)] = (path, ln, (m.group(1).strip() + (m.group(3) or '')).strip())

by_file = defaultdict(list)
for name, (addr, size, typ) in syms.items():
    path, ln, ctype = defs.get(name, ('(not defined in src/: asm data, Psy-Q libraries or overlays)', 0, ''))
    by_file[path].append((addr, name, size, typ or ctype, ln))

with open(OUT, 'w') as f:
    f.write('# Executable global variables by source file\n\n')
    f.write(f'Generated by `tools/dev/symbol_docs.py` from `decomp/config/us/symbols.txt` '
            f'({len(syms)} data symbols, {len(defs)} located in `decomp/src/`). '
            'RAM addresses of the USA version (original executable). File offset = RAM − 0x80090000 '
            '(only for what lies below 0x80134C4C; the rest is bss).\n\n')
    f.write('## Index\n\n')
    for path in sorted(by_file, key=lambda p: (p.startswith('('), p)):
        f.write(f'- [{path}](#{re.sub(r"[^a-z0-9]+", "-", path.lower()).strip("-")}) ({len(by_file[path])})\n')
    for path in sorted(by_file, key=lambda p: (p.startswith('('), p)):
        f.write(f'\n## {path}\n\n| Address | Symbol | Size | Type | Line |\n|---|---|---|---|---|\n')
        for addr, name, size, typ, ln in sorted(by_file[path]):
            f.write(f'| `{addr:#010x}` | `{name}` | {size:#x} | `{typ}` | {ln or ""} |\n' if size else
                    f'| `{addr:#010x}` | `{name}` | | `{typ}` | {ln or ""} |\n')
print(f'{OUT}: {len(syms)} symbols, {len(defs)} with a file, {len(by_file)} files')
