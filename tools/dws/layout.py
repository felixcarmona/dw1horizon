"""The directory layout of story sources (docs/mods/dws.md section 1) and the writer that
lands the decompiler's output in it:

    story/base/zones/<zone>/s<ID>-<screens>/script.dws          port header: tail, entries, includes
                                            sec<NNN>-<role>.dws one file per section chunk (a `part { }`)
                                            README.md
    story/base/zones/<zone>/README.md
    story/base/maphead/                                          the global entry points and screen setups

Every file holds keys, never game text. The include order is the address order, so the compile of the
directory is byte-identical to the disc (`dws.py roundtrip --layout`)."""
import os, re, sys
from . import decomp, textx
from dws import bytecode

ROLES = [(range(5, 13), lambda n: f'talk-slot{n - 5}'), (range(51, 80), lambda n: f'step-tile{n - 51}'),
         (range(80, 110), lambda n: f'use-tile{n - 80}'), (range(110, 120), lambda n: f'exit{n - 110}')]
SPECIAL = {254: 'enter', 255: 'screen-setup', 1: 'section1', 2: 'section2', 3: 'section3', 4: 'section4'}
SCREENS = re.compile(r'^; screens that load it \(SET_SCRIPT in MAPHEAD\): (.*)$', re.M)
README_NAMES = {'zones': 'screens, grouped by the zone of the first screen that loads each script'}


def slug(s):
    s = re.sub(r"[^a-z0-9]+", '-', s.lower().replace("'", '')).strip('-')
    return s or 'unnamed'


def screens_of(text):
    m = SCREENS.search(text)
    if not m: return []
    out = []
    for part in m.group(1).split(', '):
        mm = re.match(r'(\d+) (.*)$', part.strip())
        if mm: out.append((int(mm.group(1)), mm.group(2)))
    return out


def role(secid):
    if secid in SPECIAL: return SPECIAL[secid]
    for r, f in ROLES:
        if secid in r: return f(secid)
    return 'section'


def chunk_file(names, secs):
    ids = {lab: s for s, lab, _ in secs}
    sid = next((ids[n] for n in names if n in ids), None)
    if sid is None: return 'head', 'head'
    return f'sec{sid:03d}-{role(sid)}', role(sid)


def write(out_root, dg=None, maphead=None, stats=None):
    """Writes the whole disc under out_root. Returns {script id: path of its script.dws} and the maphead path."""
    import tempfile
    d, m = textx.disassemble(None, dg, maphead)
    index = {}
    zones = {}
    os.makedirs(os.path.join(out_root, 'zones'), exist_ok=True)
    for rp, txt in (('README.md', '# base\n\nThe ported original game, decompiled (`dws decompile-all`). See story/README.md.\n'),
                    (os.path.join('zones', 'README.md'), '# zones\n\nOne folder per zone (named after the first screen that loads the script); inside, one folder per original script.\n')):
        if not os.path.exists(os.path.join(out_root, rp)): open(os.path.join(out_root, rp), 'w').write(txt)
    for f in sorted(os.listdir(d)):
        mm = re.match(r'script_(\d+)\.scn\.txt$', f)
        if not mm or int(mm.group(1)) == 0 and False: continue
        sid = int(mm.group(1)); text = open(os.path.join(d, f), encoding='utf-8').read()
        scr = screens_of(text)
        if sid == 0: zone = 'unused'
        elif scr: zone = slug(scr[0][1])
        else: zone = 'libraries'
        sname = f's{sid:03d}' + ('-' + '-'.join(str(a) for a, _ in scr[:3]) if scr else '')
        sdir = os.path.join(out_root, 'zones', zone, sname); os.makedirs(sdir, exist_ok=True)
        head, chunks, secs = decomp.lift_chunks(text, 'script', sid, f, stats)
        incl = []; table = []
        used = {}
        for names, lines in chunks:
            fn, r = chunk_file(names, secs)
            if fn in used: used[fn] += 1; fn = f'{fn}-{used[fn]}'
            else: used[fn] = 0
            fn += '.dws'; incl.append(fn); table.append((fn, r, len([l for l in lines if l.startswith('    ')])))
            open(os.path.join(sdir, fn), 'w', encoding='utf-8').write('part {\n' + '\n'.join(lines).rstrip('\n') + '\n}\n')
        body = [f'script {sid} port {{'] + ['    ' + h for h in head] + [''] + [f'    include "{fn}";' for fn in incl] + ['}', '']
        open(os.path.join(sdir, 'script.dws'), 'w', encoding='utf-8').write(
            f'// script {sid} of DG.SCN, decompiled (port form). Keys only: the text is in text/us/.\n' + '\n'.join(body))
        rd = [f'# Script {sid}', '', f'Screens that load it: {", ".join(f"{a} {b}" for a, b in scr) or "none (a library script)"}.', '',
              'Generated by `dws decompile-all`; compiles back to the original bytes. Files, in address order:', '',
              '| file | what | instructions |', '|---|---|---|'] + [f'| `{fn}` | {r} | {n} |' for fn, r, n in table]
        open(os.path.join(sdir, 'README.md'), 'w', encoding='utf-8').write('\n'.join(rd) + '\n')
        index[sid] = os.path.join(sdir, 'script.dws'); zones.setdefault(zone, []).append((sname, scr))
    for zone, lst in zones.items():
        rd = [f'# Zone: {zone.replace("-", " ")}', '', 'Scripts of this zone (one folder each):', '']
        for sname, scr in lst: rd.append(f'- `{sname}`: ' + (', '.join(f'{a} {b}' for a, b in scr[:6]) + (' ...' if len(scr) > 6 else '') if scr else 'library'))
        open(os.path.join(out_root, 'zones', zone, 'README.md'), 'w', encoding='utf-8').write('\n'.join(rd) + '\n')
    # MAPHEAD
    text = open(os.path.join(m, 'maphead.scn.txt'), encoding='utf-8').read()
    mdir = os.path.join(out_root, 'maphead'); os.makedirs(mdir, exist_ok=True)
    head, chunks, secs = decomp.lift_chunks(text, 'maphead', None, 'maphead', stats)
    incl = []; ids = {lab: s for s, lab, _ in secs}
    for names, lines in chunks:
        sid = next((ids[n] for n in names if n in ids), None)
        fn = ('head' if sid is None else (f'screen{sid:03d}' if sid <= 254 else f'global-{sid:04d}')) + '.dws'
        if fn in incl: fn = f'dup-{len(incl)}-{fn}'
        incl.append(fn)
        open(os.path.join(mdir, fn), 'w', encoding='utf-8').write('part {\n' + '\n'.join(lines).rstrip('\n') + '\n}\n')
    body = ['maphead port {'] + ['    ' + h for h in head] + [''] + [f'    include "{fn}";' for fn in incl] + ['}', '']
    open(os.path.join(mdir, 'maphead.dws'), 'w', encoding='utf-8').write('// MAPHEAD.SCN, decompiled (port form).\n' + '\n'.join(body))
    open(os.path.join(mdir, 'README.md'), 'w', encoding='utf-8').write(
        '# MAPHEAD\n\nThe per-screen setup sections (`screenNNN.dws`: who stands where by hour and flags, music, which script loads) '
        'and the global entry points the C code calls (`global-NNNN.dws`: shopkeeper lines, new game, death, medals).\n')
    return index, os.path.join(mdir, 'maphead.dws')
