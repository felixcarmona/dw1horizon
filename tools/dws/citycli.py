"""dws city-extract | city-compile | city-verify | why (docs/mods/city-rules.md)."""
import os, sys
from . import city, build as B
from .diag import DwsError

DEFAULT = os.path.join(B.ROOT, 'story', 'base', 'city', 'city.dws')
PRESENCE_README = """# presence/

Who stands on which screen, and when: one file per screen (`s<MAPHEAD section>.dws`), {rules} NPC rules on {n} screens, written by
`python3 tools/dws.py city-extract` from the original MAPHEAD.SCN. In the original this is code (the screen's setup section: `IF` chains over
triggers, the clock and a random draw, then `LOAD_DIGIMON` / `SET_DIGIMON`); here it is one declaration per NPC: `npc Species slot K [autotalk] when CONDITION;`.
A File City screen decides with a counter (at most 3 Digimon, in priority order), which a flat condition cannot say shortly: those files name the
branch points (`let r12 = ...;`) and the NPCs refer to them.

Not generated by hand: do not edit. `python3 tools/dws.py city-verify story/base/city/city.dws story/base/city/presence/*.dws` runs the original
instructions and these declarations on the same states and compares who is placed. `python3 tools/dws.py why NPC --recruit Angemon ...` explains one NPC.
Declarations are not compiled into MAPHEAD yet (the engine runs the original section): see docs/mods/city-rules.md, "What is left".
"""


def load_spec(path):
    """The `city { }` declaration of a file (no other content needed)."""
    from .parser import Parser
    src = open(path, encoding='utf-8').read()
    p = Parser(src, path); nodes = [n for n in p.parse_file()]
    cities = [n for n in nodes if n.kind == 'city']
    if not cities: raise DwsError(f'{path}: no city {{ }} declaration')
    spec = {}
    for c in cities:
        city.check(c.spec, c.pos)
        for blk in c.spec:
            if blk in spec: raise DwsError(f'{path}: "{blk}" is declared twice')
        spec.update(c.spec)
    return spec


def load_specs(paths):
    """several declaration files (and the presence directory when it is named) -> one spec"""
    spec = {}
    for pth in paths:
        files = sorted(os.path.join(pth, f) for f in os.listdir(pth) if f.endswith('.dws')) if os.path.isdir(pth) else [pth]
        for f in files:
            s = load_spec(f)
            if 'presence' in s and 'presence' in spec: spec['presence'].update(s.pop('presence'))
            for blk in s:
                if blk in spec: raise DwsError(f'{f}: "{blk}" is declared twice')
            spec.update(s)
    return spec


def run(a):
    if a.cmd == 'city-extract':
        spec = city.extract_original(a.src)
        out = a.o or DEFAULT
        os.makedirs(os.path.dirname(out), exist_ok=True)
        open(out, 'w', encoding='utf-8').write(city.to_dws(spec))
        if not a.no_presence:
            from . import presence as PR
            pres, skipped = PR.extract_all()
            pdir = os.path.join(os.path.dirname(out), 'presence')
            os.makedirs(pdir, exist_ok=True)
            for f in os.listdir(pdir):
                if f.startswith('s') and f.endswith('.dws'): os.remove(os.path.join(pdir, f))
            for sid, sc in pres.items():
                open(os.path.join(pdir, f's{sid:03d}.dws'), 'w', encoding='utf-8').write(city.to_dws(
                    {'presence': {sid: sc}}, header=f'Who stands on screen {sid} ({PR.screen_name(sid)}), and when. Read out of MAPHEAD.SCN section {sid} by `dws city-extract`;\n'
                                                    '// `dws city-verify` proves it against the original instructions (docs/mods/city-rules.md).'))
            open(os.path.join(pdir, 'README.md'), 'w').write(PRESENCE_README.format(n=len(pres), rules=sum(len(s['npcs']) for s in pres.values()), skipped=len(skipped)))
            if skipped:
                open(os.path.join(pdir, 'skipped.txt'), 'w').write(''.join(f'{k}\t{v}\n' for k, v in sorted(skipped.items())))
            print(f'{os.path.relpath(pdir, B.ROOT)}/s*.dws: {sum(len(v["npcs"]) for v in pres.values())} NPC rules on {len(pres)} screens ({sum(1 for v in pres.values() if v["form"] == "circuit")} with named conditions); '
                  f'{len(skipped)} sections not readable (loops)')
        print(f'{os.path.relpath(out, B.ROOT)}: {len(spec["prosperity"])} prosperity rules, {len(spec["top_map"]["rows"]) + 1} top-map rows, '
              f'{len(spec["revival"]["rows"]) + 1} revival rows, {len(spec["shop_maps"])} shop maps, {len(spec["arena_maps"])} arena maps, '
              f'{len(spec["start"]["inventory"])} start stacks')
        return 0
    if a.cmd == 'city-compile':
        spec = load_spec(a.file or DEFAULT); blob = city.encode(spec)
        if a.bin: open(a.bin, 'wb').write(blob)
        if a.c_header: open(a.c_header, 'w').write(city.to_c_header(blob))
        print(f'city table: {len(blob)} bytes' + (f' -> {a.bin}' if a.bin else '') + (f', header {a.c_header}' if a.c_header else ''))
        return 0
    if a.cmd == 'city-verify':
        from . import cityproof
        return cityproof.verify(load_specs(a.files or [DEFAULT, os.path.join(os.path.dirname(DEFAULT), 'presence')]))
    if a.cmd == 'why':
        from .py import why as PW                  # an NPC of a mod written in Python: its presence and its guard chain
        files = PW.mods_files(getattr(a, 'mods', None) or None)
        if PW.why(a.what, getattr(a, 'as_', None), files=files): return 0
        from . import cityproof
        from .diag import DwsError
        try:
            return cityproof.why(a)
        except DwsError as e:
            if 'not an NPC species' not in e.msg: raise
            if PW.why_name(a.what): return 0
            where = ', '.join(getattr(a, 'mods', None) or []) or 'story/mods/*/src'
            e.msg = (f'"{a.what}": no NPC of that name in the mods written in Python ({len(files)} files in {where}; a mod elsewhere: '
                     f'python3 tools/dws.py why {a.what} PATH/TO/MOD), and not a species of the game nor one of top_map, revival, prosperity')
            raise
