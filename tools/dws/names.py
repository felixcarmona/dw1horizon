"""Names for what the original game uses (pstats, triggers, animations), derived from engine data, and the list of what is still unnamed.

    python3 tools/dws.py names            # rewrite the generated blocks of story/names.toml and build/story-analysis/names-todo.csv
    python3 tools/dws.py names --check    # nothing written; fail if the generated blocks are out of date

What is derived (and where from, written beside every entry in story/names.toml):
  * `decomp/include/dw/pstat.h` and `trigger.h`: the symbolic names of the decompilation (`PSTAT_TOURNAMENT_ID`, `TRIGGER_HAVE_OLD_FISHROD`);
  * nothing else. Meanings written in prose in a research notes file are *not* names: they are reported as a hint in names-todo.csv
    to be turned into a name. No meaning is guessed.

`names-todo.csv`: the 30 most used pstats/triggers that still have no name (usage counts, the scripts/sections that use them most, the
nearest line of text, the doc row that mentions them)."""
import csv, json, os, re
from . import lift, readable, textx, build as B

ROOT = B.ROOT
DECOMP = os.path.join(ROOT, 'decomp', 'include', 'dw')
TOML = os.path.join(ROOT, 'story', 'names.toml')
TODO = os.path.join(ROOT, 'build', 'story-analysis', 'names-todo.csv')
BEGIN = '# >>> generated by `dws names` from {src} (do not edit by hand; a hand entry above wins and removes the generated one) >>>'
END = '# <<< generated <<<'
RECRUIT = range(200, 312)          # triggers 200 + species are `is_recruited(..)`, not names


def header_names(fname, prefix):
    """{number: (SYMBOL, alias symbol)} of `#define PREFIX_NAME PREFIX_N` lines of a decomp header."""
    out = {}
    for line in open(os.path.join(DECOMP, fname), encoding='utf-8'):
        m = re.match(rf'#define\s+({prefix}_[A-Z0-9_]+)\s+{prefix}_(\d+)\s*$', line.strip())
        if m and not re.fullmatch(rf'{prefix}_\d+', m.group(1)): out[int(m.group(2))] = m.group(1)
    return out


def word(sym, prefix):
    """TRIGGER_D_RANK_CUP_WON -> cup_won.d_rank ; PSTAT_TOURNAMENT_ID -> tournament_id ; TRIGGER_HAVE_OLD_FISHROD -> have_old_fishrod."""
    w = sym[len(prefix) + 1:].lower()
    m = re.fullmatch(r'(.+)_cup_won', w)
    if m: return 'cup_won.' + m.group(1)
    return w


def taken(path):
    """Numbers named by hand (not in a generated block) in names.toml, and by the `alias`es of story/core."""
    names = lift.Names(toml_path=os.devnull)
    hand = {'vars': set(names.vars), 'flags': set(names.flags)}
    if os.path.exists(path):
        txt = strip_blocks(open(path, encoding='utf-8').read())
        import tomllib
        d = tomllib.loads(txt)
        hand['vars'] |= {int(k) for k in d.get('vars', {})}; hand['flags'] |= {int(k) for k in d.get('flags', {})}
    return hand


def strip_blocks(text):
    return re.sub(r'# >>> generated by.*?# <<< generated <<<\n', '', text, flags=re.S)


def block(src, entries):
    lines = [BEGIN.format(src=src)]
    for n, nm, sym in sorted(entries): lines.append(f'{n} = "{nm}"'.ljust(40) + f'# {sym}')
    lines.append(END)
    return '\n'.join(lines) + '\n'


def generate(path=TOML, write=True):
    """Rewrites the generated blocks of names.toml. -> the new text."""
    text = strip_blocks(open(path, encoding='utf-8').read())
    hand = taken(path)
    pst = {n: s for n, s in header_names('pstat.h', 'PSTAT').items() if n not in hand['vars']}
    trg = {n: s for n, s in header_names('trigger.h', 'TRIGGER').items() if n not in hand['flags'] and n not in RECRUIT}
    used = set()
    def entries(d, prefix):
        out = []
        for n, s in d.items():
            nm = word(s, prefix)
            if nm in used: continue
            used.add(nm); out.append((n, nm, f'decomp/include/dw/{prefix.lower()}.h {s}'))
        return out
    ev = entries(pst, 'PSTAT'); ef = entries(trg, 'TRIGGER')
    def put(text, table, ents, src):
        m = re.search(rf'^\[{table}\]\s*$', text, flags=re.M)
        nxt = re.search(r'^(\[\w+\]|# NPC names)', text[m.end():], flags=re.M)
        at = m.end() + (nxt.start() if nxt else len(text) - m.end())
        head = text[:at].rstrip('\n') + '\n'
        return head + (block(src, ents) + '\n' if ents else '\n') + text[at:]
    text = put(text, 'vars', ev, 'decomp/include/dw/pstat.h')
    text = put(text, 'flags', ef, 'decomp/include/dw/trigger.h')
    if write: open(path, 'w', encoding='utf-8').write(text)
    return text


# ------------------------------------------------------------------------------------------------ the todo list
def doc_rows():
    """[(first, last, 'Trigger'|'Pstat', text)] of the tables of a research notes file (prose, a hint only; none here)."""
    rows = []; kind = None
    notes = os.path.join(ROOT, 'docs', 'game', '03-scripts.md')
    for line in (open(notes, encoding='utf-8') if os.path.exists(notes) else ()):
        if line.startswith('## Pstats'): kind = 'pstat'
        elif line.startswith('There are **800 bits**'): kind = 'trigger'
        if kind and line.startswith('|'):
            c = [x.strip() for x in line.strip().strip('|').split('|')]
            m = re.match(r'(?:\*\*)?(\d+)(?:\s*[–-]\s*(\d+))?', c[0])
            if m and len(c) >= 3:
                a = int(m.group(1)); b = int(m.group(2) or a)
                rows.append((a, b, kind, ' '.join(x for x in c[1:3] if x)[:230]))
    return rows


def todo(limit=30, out=TODO):
    scripts, mh = readable.disc_texts()
    names = lift.Names(); bank = json.load(open(os.path.join(ROOT, 'text', 'us', 'dialogue.json'), encoding='utf-8'))
    trig = {}; pst = {}
    def note(table, n, where, near, role):
        e = table.setdefault(n, {'uses': 0, 'sets': 0, 'reads': 0, 'where': {}, 'near': {}})
        e['uses'] += 1; e[role] += 1; e['where'][where] = e['where'].get(where, 0) + 1
        if near and where not in e['near']: e['near'][where] = near
    def walk(text, kind, sid, fname):
        for sec in lift.split_sections(text, kind, sid, fname):
            where = f'{"MH" if kind == "maphead" else sid}:{sec.sid if sec.sid is not None else sec.label}'
            for i, x in enumerate(sec.ins):
                def near():
                    for d in (0, 1, -1, 2, -2, 3, -3, 4, -4):
                        if 0 <= i + d < len(sec.keys) and sec.keys[i + d]:
                            if bank.get(sec.keys[i + d][0]): return sec.keys[i + d][0]          # the key only: the game's own text is never written into the repository
                    return ''
                n = x.name
                if n in ('SET_TRIGGER', 'UNSET_TRIGGER'): note(trig, int(x.args[0]), where, near(), 'sets')
                if n == 'IF':
                    for c in x.args[:-1]:
                        m = re.search(r'\btrigger (\d+)', c)
                        if m: note(trig, int(m.group(1)), where, near(), 'reads')
                        m = re.search(r'\bp(\d+) ', c)
                        if m: note(pst, int(m.group(1)), where, near(), 'reads')
                elif n in ('SET_PSTAT', 'ADD_TO_PSTAT', 'REDUCE_PSTAT') or n.startswith('STORE_'):
                    m = re.fullmatch(r'p(\d+)', x.args[0]) if x.args else None
                    if m: note(pst, int(m.group(1)), where, near(), 'sets')
                elif n in ('SWITCH',):
                    m = re.fullmatch(r'p(\d+)', x.args[0])
                    if m: note(pst, int(m.group(1)), where, near(), 'reads')
    for sid, (path, text) in scripts.items(): walk(text, 'script', sid, path)
    walk(mh, 'maphead', None, 'maphead')
    hand = taken(TOML)
    gen = generate(write=False)
    import tomllib
    d = tomllib.loads(gen)
    named_v = set(names.vars) | {int(k) for k in d.get('vars', {})}
    named_f = set(names.flags) | {int(k) for k in d.get('flags', {})}
    docs = doc_rows()
    rows = []
    for kind, table, named in (('trigger', trig, named_f), ('pstat', pst, named_v)):
        for n, e in table.items():
            if n in named or (kind == 'trigger' and n in RECRUIT): continue
            top = sorted(e['where'].items(), key=lambda kv: -kv[1])[:4]
            hint = next((t for a, b, k, t in docs if k == kind and a <= n <= b), '')
            rows.append({'kind': kind, 'number': n, 'uses': e['uses'], 'sets': e['sets'], 'reads': e['reads'], 'scripts': len(e['where']),
                         'top_sections': ' '.join(f'{w}x{c}' for w, c in top), 'nearest_key': e['near'].get(top[0][0], '') if top else '',
                         'doc_hint_not_a_name': hint})
    rows.sort(key=lambda r: (-r['uses'], r['kind'], r['number']))
    rows = rows[:limit]
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, list(rows[0])); w.writeheader(); w.writerows(rows)
    return rows
