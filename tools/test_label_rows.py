"""The labels of a screen row stand on one line, the line the English original's labels stand on, and the labels of a
list start where its other words start.

Each label is a crop of SYSTEM_W (tools/localize/labels.py draws the translated words; crop tables in
src/main/game_menu.c, regenerated by tools/localize/systemw.py crop_tables, place them). A word's line is the row most
of its letters stand on: the lowest with two columns of ink at least (an accent above or a Q's tail below does not
move it). Checked on the status page, the technique page's Techset and Final header rows (beside the original MP), the
change-techniques grid's element names and its panel (beside the original MP and arrows): in every language each
label's line is the English label's (the Spanish one's for the names English draws in another texture). Japanese and
Chinese letters have no line: their lowest ink stands on it instead."""
import contextlib
import io
import os
import re
import tempfile
import unittest

from tools.languages import CODES

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXTRACTED = os.path.join(ROOT, 'extracted', '')
MACROS = {'es': 'ES', 'pt-br': 'PT_BR', 'fr': 'FR', 'de': 'DE', 'it': 'IT', 'ja': 'JA', 'ca': 'CA', 'zh-hans': 'ZH'}
CJK = ('ja', 'zh-hans')

# (table, row, what): the labels checked; rows of one screen line are listed together
STATUS = [('STATS_VIEW_ELEMENTS', i, en) for i, en in (
    (3, 'NAME'), (4, 'DIGI'), (5, 'WEIGHT'), (6, 'AGE'), (7, 'TYPE'), (8, 'SPECIAL'), (9, 'ACTIVE'),
    (17, 'HAPPINESS'), (18, 'SPEED'), (19, 'BRAINS'))]
HEADER = [('MOVES_VIEW_TECHSET_TEXT', i, en) for i, en in enumerate(('POWER', 'RANG', 'SPEC', 'MP'))]
PANEL = [('MOVES_SELECTED_LABELS', i, en) for i, en in enumerate(('TECH. DATA', 'POWER', 'MP', 'RANG', 'SPEC'))]
ELEMENTS = [('MOVES_VIEW_ELEMENT_NAMES', i, en) for i, en in enumerate(
    ('FIRE', 'BATTLE', 'AIR', 'NATURE', 'ICE', 'MECH', 'FILTH', 'DARK', 'LIGHT', 'WATER', 'WEAPON', 'EARTH'))]
# a separate bug, not a line: the Chinese menu word 道具 is drawn over the Chinese filth name's cell
KNOWN = {('zh-hans', 'elements', 'FILTH')}


def decomp():
    for path in (os.environ.get('DW_SELFTEST_DECOMP'), os.path.join(ROOT, 'build', 'decomp-dev'),
                 os.path.join(ROOT, 'build', 'decomp-int')):
        if path and os.path.exists(os.path.join(path, 'src', 'main', 'game_menu.c')):
            return path
    return None


def s16(x):
    return x - 65536 if x >= 32768 else x


def table(source, name, language):
    """-> the crop rows {posX, posY, w, h, texX, texY} the language's build compiles for the table"""
    begin = source.index('IconRect ' + name + '[')
    body = source[begin:source.index('\n};', begin)]
    block = re.search(r'#if MOD_LANG_BUILD.*?#endif', body, re.S)
    parts = re.split(r'(#(?:el)?if MOD_LANG_BUILD == MOD_LANG_\w+|#else)', block.group(0))
    variants, key = {}, None
    for part in parts:
        m = re.match(r'#(?:el)?if MOD_LANG_BUILD == MOD_LANG_(\w+)', part)
        if m or part == '#else':
            key = m.group(1) if m else 'EN'
        elif key:
            variants[key] = part

    def rows(text):
        return [[int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]+)', line)]
                for line in text.splitlines() if line.strip().startswith('{ 0x')]
    return rows(body[:block.start()]) + rows(variants[MACROS.get(language, 'EN')]) + rows(body[block.end():])


def final_y(source):
    """-> f(posY): the y renderDigimonMovesView draws a Techset header crop at on the Final row"""
    begin = source.index('icon = &MOVES_VIEW_TECHSET_TEXT[i];\n\t\t\trenderRectPolyFT4(icon->posX, ')
    expression = source[begin:].split('renderRectPolyFT4(icon->posX, ', 1)[1].split(',', 1)[0].strip()
    if re.fullmatch(r'-?(0x[0-9a-fA-F]+|\d+)', expression):
        return lambda y: int(expression, 0)
    m = re.fullmatch(r'icon->posY \+ (0x[0-9a-fA-F]+|\d+)', expression)
    if not m:
        raise ValueError(f'the Final row\'s y is {expression!r}')
    return lambda y: y + int(m.group(1), 0)


def texture(path):
    from tools.localize.build import tim_entries
    with open(path, 'rb') as f:
        data = f.read()
    start, _, w, h = tim_entries(data)[0]
    return w, [v for b in data[start:start + w * h // 2] for v in (b & 15, b >> 4)]


# the status tags' and TYPE/SPECIAL/ACTIVE's palette: background 0, outline or shadow 1 (elsewhere 15 and 13)
TAG_PALETTE = {'NAME', 'DIGI', 'WEIGHT', 'AGE', 'TYPE', 'SPECIAL', 'ACTIVE'}


def line(tim, crop, y, cjk=False, blank=(0, 13, 15)):
    """-> (the word's line on screen, its top, its left, its right) for a crop drawn at y; None if no ink. Ink is any
    index but the cell's background and outline or shadow."""
    w, px = tim
    x0, _, cw, ch, u, v = crop
    v &= 127
    cells = [px[(v + j) * w + u:(v + j) * w + u + cw] for j in range(ch)]
    rows = [j for j in range(ch) if any(c not in blank for c in cells[j])]
    if not rows:
        return None
    columns = [i for i in range(cw) if any(cells[j][i] not in blank for j in range(ch))]
    # a line has the feet of two letters at least (a Q's tail alone below it is not one)
    base = rows[-1] if cjk else max(j for j in rows if sum(c not in blank for c in cells[j]) >= 2)
    return y + base, y + rows[0], s16(x0) + columns[0], s16(x0) + columns[-1]


def lines(source, tims, language):
    """-> {(group, what): (line, top, left, right)} of every checked label in the language's build"""
    out = {}
    cjk = language in CJK
    final = final_y(source)
    for group, labels in (('status', STATUS), ('header', HEADER), ('panel', PANEL), ('elements', ELEMENTS)):
        for name, i, what in labels:
            crop = table(source, name, language)[i]
            native = what == 'MP'
            blank = (0, 1) if what in TAG_PALETTE else (0, 13, 15)
            out[group, what] = line(tims[language], crop, s16(crop[1]), cjk and not native, blank)
            if group == 'header' and not native:
                # (the same cell in SYSTEM_W's copy in ETCTIM.BIN, which labels.py draws alike)
                out['final', what] = line(tims[language], crop, final(s16(crop[1])), cjk)
    return out


@unittest.skipUnless(decomp() and os.path.exists(EXTRACTED + 'ETCDAT/SYSTEM_W.TIM'),
                     'needs a prepared decomp (build/decomp-dev) and the USA disc in extracted/')
class LabelRows(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        from tools.localize import build as L
        with open(os.path.join(decomp(), 'src', 'main', 'game_menu.c')) as f:
            cls.source = f.read()
        cls.tims = {'en': texture(EXTRACTED + 'ETCDAT/SYSTEM_W.TIM')}
        os.makedirs(os.path.join(ROOT, 'build'), exist_ok=True)
        for language in CODES[1:]:
            with tempfile.TemporaryDirectory(dir=os.path.join(ROOT, 'build')) as d, \
                    contextlib.redirect_stdout(io.StringIO()):
                L.build(d + '/out', EXTRACTED, scratch=d + '/scratch', language=language)
                cls.tims[language] = texture(os.path.join(d, 'out', language, 'ETCDAT', 'SYSTEM_W.TIM'))
        cls.lines = {language: lines(cls.source, cls.tims, language) for language in CODES}

    def test_every_label_stands_on_the_english_line(self):
        english = self.lines['en']
        for language in CODES[1:]:
            for (group, what), found in self.lines[language].items():
                if (language, group, what) in KNOWN:
                    continue
                # (the new rows' English names are not in SYSTEM_W's cells: Spanish stands where they do)
                reference = english[group, what] or self.lines['es'][group, what]
                with self.subTest(language=language, row=group, label=what):
                    self.assertIsNotNone(found)
                    self.assertEqual(found[0], reference[0])

    def test_the_labels_of_one_line_stand_on_it_together(self):
        for language in CODES:
            found = self.lines[language]
            for group, members in (('header', ('POWER', 'RANG', 'SPEC', 'MP')), ('final', ('POWER', 'RANG', 'SPEC')),
                                   ('status', ('TYPE', 'SPECIAL', 'ACTIVE')), ('status', ('WEIGHT', 'AGE'))):
                with self.subTest(language=language, row=group, labels=members):
                    self.assertEqual(len({found[group, what][0] for what in members}), 1,
                                     {what: found[group, what] for what in members})

    def test_the_final_row_is_the_header_row_moved_down_as_in_english(self):
        english = self.lines['en']
        for language in CODES:
            for what in ('POWER', 'RANG', 'SPEC'):
                with self.subTest(language=language, label=what):
                    found = self.lines[language]
                    self.assertEqual(found['final', what][0] - found['header', what][0],
                                     english['final', what][0] - english['header', what][0])

    def test_the_labels_of_a_list_start_where_the_others_do(self):
        """The status page's stat names start where the native words of their list start (STAT_LEFT: Tired, Off. and
        Def., three columns right of the original's own smaller-font names) and end before their bars; the technique
        panel's labels start at the English labels' first column. In every language, with no exception: a word that
        does not fit is shortened or drawn narrower, never moved"""
        from tools.localize.systemw import STAT_LEFT, STAT_END
        english = self.lines['en']
        for what in STAT_END:
            self.assertEqual(english['status', what][2], STAT_LEFT[what] - 3)
        for language in CODES[1:]:
            found = self.lines[language]
            for group, what in [('status', w) for w in STAT_END] + [('panel', w) for w in
                                                                    ('TECH. DATA', 'POWER', 'RANG', 'SPEC')]:
                with self.subTest(language=language, row=group, label=what):
                    left, right = found[group, what][2:]
                    if group == 'status':
                        self.assertEqual(left, STAT_LEFT[what])
                        self.assertLessEqual(right, STAT_END[what])
                    else:
                        self.assertEqual(left, english[group, what][2])

    def test_the_technique_headers_start_over_their_columns_and_never_touch(self):
        """In every translated language, POWER, MP, RANG and SPEC (and the Final row's three) start exactly over the
        first pixel of their value column (the power's digits, the dots before the MP cost and the range, the dot
        before the effect icon), and each one's letters end TECH_HEADER_GAP columns before the next header's (two
        clear columns between their outlines), the last one's before the frame: a word that would not is shortened
        or drawn narrower, never moved. English keeps the original's headers."""
        from tools.localize.systemw import TECH_HEADER_GAP, TECH_HEADER_END, TECH_HEADER_LEFT, TECH_MP_LEFT, TECH_MP
        order = ('POWER', 'MP', 'RANG', 'SPEC')
        columns = (TECH_HEADER_LEFT[0], TECH_MP_LEFT) + TECH_HEADER_LEFT[1:]
        self.assertEqual(self.lines['en']['header', 'MP'][2:], TECH_MP[1:])
        for language in CODES[1:]:
            found = self.lines[language]
            for group in ('header', 'final'):
                spans = [found[group if what != 'MP' else 'header', what][2:] for what in order]
                with self.subTest(language=language, row=group):
                    self.assertEqual([left for left, _ in spans], list(columns), spans)
                    for (what, (left, right)), (_, (next_left, _)) in zip(zip(order, spans), zip(order[1:], spans[1:])):
                        self.assertGreaterEqual(next_left - right, TECH_HEADER_GAP, (what, spans))
                    self.assertLessEqual(spans[-1][1], TECH_HEADER_END, spans)
            for what in ('POWER', 'RANG', 'SPEC'):
                with self.subTest(language=language, label=what):
                    self.assertEqual(found['final', what][2:], found['header', what][2:])

if __name__ == '__main__':
    unittest.main()
