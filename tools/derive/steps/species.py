"""DIGI.DAT, the archive of the species the disc carries beyond the executable's 180 (build-full.sh).

What the bash did with four processes and an environment is done here with the functions of tools/species.py, in
this process: `select` (the build's species folder build/NAME/species: the 180 originals and the selected imports,
paths under build/models, build/dcb, build/dw2 pointed to build/NAME/models), the partner model buffer (`maxmodel` and
the sizes of the `disc-files` models, at least the original 0x18800, whole sectors) and `build`. The settings the bash
took from the tree $W come from the executable's facts (facts.py): COLD (unless the environment sets it), SPECIES_RAM_MB
8 when the tree has the 8 MB buffer, EVL_SHARD_SCRATCH_SIZE (5436 and a warning without it). The selection is the
bash's: SPECIES (default 180 181 182 373; empty with IMPORTS=0), EXTRA_SPECIES, and the folders the providers make.

Providers (provide_models(ctx) -> {id: (model file, texture file or None, (model sha1, texture sha1 or None))}): the
models made from the player's discs and committed recipes/deltas come from a provider, and every file a
provider hands over is pinned by its SHA-1 in recipes/species-pins.json (`python3 -m tools.derive.steps.species pin`
writes them all): a missing file stops the build with the list (prepare the remaining private inputs); other
bytes stop only the player's path (--strict), a developer build rewrites those pins and says which (rule in pinned()).
  imports           the 175 imported models, generated from the player's discs and plain MD3 deltas by
                    steps/imports.py into imported-models; 65 receive a field overlay in steps/overlays.py (one unit each).
                    SPECIES_PROVIDER=imports (the everything recipe's species.provider). It replaces the four imports the
                    bash converted (build-full.sh Veemon, Puppetmon, Kimeramon, WarGreymon), which a disc with
                    it never read
  record_originals  originals carried by a DIGI.DAT record, generated by steps/record_originals.py
                    from the player's disc and plain MD3 deltas; checked when the selection carries them

Also left for the bash after it: $O/species (the lints, missing_refs, the disc's --file list) and
$O/derived/species.env (PARTNER_MMD_MAX for make, the value its own lines would have worked out).
"""
import contextlib
import hashlib
import importlib.util
import io
import json
import os
import shutil
import sys

from .. import runner

NAME = 'species'
DESCRIPTION = 'Species records and model archive'
AFTER = ('models', 'overlays', 'record_originals')   # the partner model buffer measures the partner models (disc files); the imports' overlays
FACTS = True
PINS = 'tools/derive/recipes/species-pins.json'
IMPORTED_MODELS_SCRIPT = 'content/models/imports/species.py'
DEFAULT_SELECTION = '180 181 182 373'    # build-full.sh's SPECIES default
ORIGINAL_BUFFER = 0x18800


@contextlib.contextmanager
def species_tools():
    """tools/species.py imported in this process, and forgotten afterwards with every repository module it brought
    (rule: a module with settings must not outlive its step: the next step or script imports it again)."""
    saved_path, saved = sys.path[:], set(sys.modules)
    sys.path.insert(0, os.path.join(runner.ROOT, 'tools'))
    try:
        import species
        yield species
    finally:
        sys.path[:] = saved_path
        for n in [n for n in sys.modules if n not in saved]:
            if runner._repo_module(sys.modules[n]):
                del sys.modules[n]


def _sha1(path):
    with open(path, 'rb') as f:
        return hashlib.sha1(f.read()).hexdigest()


def _abs(p):
    return p if os.path.isabs(p) else os.path.join(runner.ROOT, p)


# ------------------------------------------------------------------ providers
class ImportedModels:
    name = 'imports'

    def __init__(self, S):
        self.S = S

    def folder(self, ctx):
        return ctx.path('imported-species')

    def provide_models(self, ctx, generate=False):
        """Makes the species files of the imported models in build/NAME/imported-species with the overlays the overlays step made
        in imported-species-models (generate: makes the overlays too, one after another: the pin command)."""
        spec = importlib.util.spec_from_file_location('imported_species', os.path.join(runner.ROOT, IMPORTED_MODELS_SCRIPT))
        imported_models = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(imported_models)
        imported_models.BASE_MODELS = ctx.path('imported-models')
        made = imported_models.make(self.folder(ctx), generate=generate)
        return {t: (_abs(m), _abs(x) if x else None) for t, (m, x) in made.items()}


class RecordOriginals:
    name = 'record_originals'

    def __init__(self, S):
        self.S = S

    def provide_models(self, ctx, generate=False):
        """Models generated from the player discs; no legacy binary fallback."""
        from tools import recordoriginals
        if generate:
            recordoriginals.make(ctx.path('record-originals'))
        out = {r['id']: (ctx.path('record-originals', f'{r["id"]}.MMD'),
                          ctx.path('record-originals', f'{r["id"]}.TIM') if 'tim' in r else None)
               for r in recordoriginals.records()}
        return out


PROVIDERS = {'imports': ImportedModels, 'record_originals': RecordOriginals}


def pinned(ctx, provider, ids=None):
    """provide_models with the SHA-1 of each file checked against recipes/species-pins.json (ids: only those).

    rule: the pins bind the player's path only (a build without --write-locks: make-release, the patcher; --strict), as
    save.lock does: the models change every day in development (new field overlays), so a developer build (build-full.sh,
    --write-locks) takes what it made, rewrites
    the pins of the files whose bytes changed (or that had none) and says which (ctx.pin_notes). A missing file stops
    every build: there is nothing to build from."""
    got = provider.provide_models(ctx)
    allpins = json.load(open(os.path.join(runner.ROOT, PINS)))
    pins = allpins.setdefault(provider.name, {})
    missing, other, out = [], [], {}
    for t, files in sorted(got.items()):
        if ids is not None and t not in ids:
            continue
        sums = []
        for f, want in zip(files, pins.get(str(t)) or [None, None]):
            if f is None:
                sums.append(None)
                continue
            if not os.path.isfile(f):
                missing.append(f'{t}: {os.path.relpath(f, runner.ROOT)}')
                sums.append(None)
                continue
            h = _sha1(f)
            if h != want:
                other.append(f'{t}: {os.path.relpath(f, runner.ROOT)} is {h}, pinned {want}')
            sums.append(h)
        out[t] = (files[0], files[1], tuple(sums))
        if not missing and pins.get(str(t)) != list(sums):
            pins[str(t)] = list(sums)
    # (a developer build: build-full.sh's --write-locks; the patcher's and the browser's are not)
    if other and not missing and getattr(ctx, 'developer', True) and not runner.strict():   # the pins follow what it made
        allpins[provider.name] = dict(sorted(pins.items(), key=lambda kv: int(kv[0])))
        _write_pins(allpins)
        ctx.pin_notes = getattr(ctx, 'pin_notes', []) + [f'{provider.name} {x}' for x in other]
        return out
    if missing or other:
        why = []
        if missing:
            why.append(f'{len(missing)} generated model files missing (run derive with imports, record_originals '
                       'and overlays before species):\n  ' +
                       '\n  '.join(missing))
        if other:
            why.append(f'{len(other)} files with other bytes than pinned (a changed generator or a new model; a '
                       f'developer build without --strict rewrites the pins):\n  ' + '\n  '.join(other))
        raise SystemExit(f'species provider {provider.name}: ' + '\n'.join(why))
    return out


def providers(env):
    """The providers a build names: SPECIES_PROVIDER (comma or space separated)."""
    names = [p for p in env.get('SPECIES_PROVIDER', '').replace(',', ' ').split() if p]
    bad = [p for p in names if p not in PROVIDERS or p == 'record_originals']
    if bad:
        raise SystemExit(f'SPECIES_PROVIDER: no provider {", ".join(bad)} (imports)')
    return names


# ------------------------------------------------------------------ the step
def settings(ctx):
    """The tree's settings as build-full.sh exports them (:94, :172, :194-195)."""
    f = ctx.facts
    cold = ctx.env.get('COLD') or ('1' if f.get('cold_anim') else '')
    ram = 8 if f.get('partner_mmd_max_8mb') is not None else int(ctx.env.get('SPECIES_RAM_MB') or '2')
    shard = f.get('evl_shard_scratch_size')
    return dict(cold=cold == '1', ram_mb=ram, shard_scratch=5436 if shard is None else shard, shard_warn=shard is None)


def outputs(ctx):
    return [('DIGI.DAT', 'DIGI.DAT'), ('species', None), ('derived/species.env', None)]


def build(ctx):
    env = ctx.env
    sel = env.get('SPECIES') or ('' if env.get('IMPORTS', '1') == '0' else DEFAULT_SELECTION)
    log = io.StringIO()
    ctx.pin_notes = []
    with ctx.calling(), species_tools() as S, contextlib.redirect_stdout(log):
        S.configure(env, **settings(ctx))
        for name in providers(env):
            p = PROVIDERS[name](S)
            got = pinned(ctx, p)
            print(f'provider {name}: {len(got)} species')
            sel += ' ' + os.path.relpath(p.folder(ctx), ctx.root)  # (the selection splits on spaces; the folder's path may have them)
        sel += ' ' + env.get('EXTRA_SPECIES', '')
        out = ctx.path('species')
        ids = S.select(sel, out, ctx.path('models'))
        print('species', ids)
        ro = {t for t, s in S.load_content(out).items() if S.is_record_original(s)}
        if ro:
            got = pinned(ctx, RecordOriginals(S), ro)
            # Route the selected records to this build's generated files before
            # measuring models, drawing icons or assembling DIGI.DAT.
            for t, s in S.load_content(out).items():
                if t not in got:
                    continue
                m, x, _ = got[t]
                s['model']['file'] = m
                if x:
                    s['texture']['file'] = x
                S.write_file(os.path.join(out, S.file_name(s)), s)
            print(f'provider record_originals: {len(ro)} species')
        # the partner model buffer (build-full.sh): the biggest partner model of the disc, at least the original
        pmm = env.get('PARTNER_MMD_MAX')
        if pmm:
            pmm = int(pmm, 0)
        else:
            need = S.max_partner_model(out)
            for _, _, f in S.disc_files(out):
                need = max(need, os.path.getsize(S.resolve_path(f)))
            pmm = (max(need, ORIGINAL_BUFFER) + 0x7FF) & ~0x7FF
        max8 = ctx.facts.get('partner_mmd_max_8mb')
        if max8 is not None and pmm > max8:
            raise SystemExit(f'a partner model of {pmm} bytes does not fit the 8 MB buffer ({max8:#x})')
        print(f'PARTNER_MMD_MAX={pmm:#X}'.replace('0X', '0x'))
        S.configure(env, partner_mmd_max=pmm, **settings(ctx))
        # rule: the species icons' cache (tools/portraits.py, keyed by the model's and texture's bytes) is the
        # repository's build/portraits-cache only in a developer build; the player's build keeps its own in its folder
        import portraits
        portraits.CACHE = portraits.CACHE if ctx.developer else ctx.path('derived', 'portraits-cache')
        # the icons the overlays step drew (steps/overlays.py: each unit into species-icons, named by their bytes' key)
        # go into that cache here, by this one process; S.build draws the rest
        icons = ctx.path('species-icons')
        if os.path.isdir(icons):
            os.makedirs(portraits.CACHE, exist_ok=True)
            n = 0
            for f in sorted(os.listdir(icons)):
                if f.endswith('.bin') and not os.path.exists(os.path.join(portraits.CACHE, f)):
                    shutil.copyfile(os.path.join(icons, f), os.path.join(portraits.CACHE, f))
                    n += 1
            print(f'icons: {n} drawn by the overlays step')
        S.build(ctx.path('DIGI.DAT'), out)
    ctx.lines.append(log.getvalue().rstrip('\n'))
    for n in ctx.pin_notes:      # (a developer build: printed, so the build log says which pins it rewrote)
        print(f'note: {PINS} rewritten: {n}')
        ctx.log(f'pin rewritten: {n}')
    os.makedirs(ctx.path('derived'), exist_ok=True)
    with open(ctx.path('derived', 'species.env'), 'w') as f:
        f.write(f'PARTNER_MMD_MAX={pmm:#X}\n'.replace('0X', '0x'))


def check(ctx):
    """species.py lint --files --quiet of the species folder and check of DIGI.DAT (build-full.sh :197)."""
    s = settings(ctx)
    env = {'COLD': '1' if s['cold'] else None, 'SPECIES_RAM_MB': str(s['ram_mb']),
           'EVL_SHARD_SCRATCH_SIZE': hex(s['shard_scratch']), 'SHARD_SCRATCH_WARN': '1' if s['shard_warn'] else None}
    ctx.run('tools/species.py', ['--content', ctx.path('species'), 'lint', '--files', '--quiet'], env=env)
    ctx.run('tools/species.py', ['--content', ctx.path('species'), 'check', ctx.path('DIGI.DAT')], env=env)
    ctx.run('tools/scriptclips.py', [ctx.path('DIGI.DAT'), '--content', ctx.path('species'), '--out', ctx.path('derived', 'script-clips.json')])


# ------------------------------------------------------------------ the pins
def pin(out):
    """Writes recipes/species-pins.json from the files the providers hand over now (imported models made into OUT)."""
    class Ctx:
        def path(self, *p): return os.path.join(out, *p)
    pins = {}
    with species_tools() as S, contextlib.redirect_stdout(io.StringIO()):
        for cls in (ImportedModels, RecordOriginals):
            got = cls(S).provide_models(Ctx(), generate=True)
            pins[cls.name] = {str(t): [_sha1(m) if os.path.isfile(m) else None, _sha1(x) if x and os.path.isfile(x) else None]
                              for t, (m, x) in sorted(got.items())}
    _write_pins(pins)
    return pins


def _write_pins(pins):
    with open(os.path.join(runner.ROOT, PINS), 'w') as f:
        f.write('{\n' + ',\n'.join(
            f' "{k}": {{\n' + ',\n'.join(f'  "{t}": {json.dumps(v)}' for t, v in d.items()) + '\n }'
            for k, d in pins.items()) + '\n}\n')


