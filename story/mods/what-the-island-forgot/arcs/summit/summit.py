def the_key():
    tamer.say("Wait! You can't hide inside the island anymore.", "The canyon, the mansion, the ice... There's nowhere down for you to go.")
    narrator.say(page("{color 7}Analogman {color 1}", "Then where...? Where do I go...?"))
    tamer.say("My key chain... It's how I got here. Someone's waiting for me on the other side of it.")
    if ask(yes="Give him the key chain", no="Keep it"):
        tamer.say("Here! Take it! Someone's waiting for me on the other side. Go!")
        key_given.set()
        sound(8, 7)
        narrator.say("The key chain flies into the light... and the light is gone.")
        tamer.say("...He's gone. Through my door.")
    else:
        tamer.say(t51.u35)
        narrator.say(t51.u36)
        tamer.say("He didn't put it back. Then we will.")
